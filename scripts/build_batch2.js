// Helper to compute Pythagorean PPI
function getPpiDerivation(w, h, d, publishedPpi) {
  const calcPpi = Math.round(Math.sqrt(w * w + h * h) / d);
  return {
    nativePpi: publishedPpi || calcPpi,
    ppiSource: publishedPpi ? 'MANUFACTURER_PUBLISHED' : 'CALCULATED',
    ppiDerivation: {
      method: 'PYTHAGOREAN_PPI',
      formula: 'sqrt(w^2 + h^2) / diagonal',
      inputs: { width: w, height: h, diagonal: d }
    }
  };
}

