interface InfinixChartInput {
  id: string;
  name: string;
  series: 'Infinix GT' | 'Infinix Zero' | 'Infinix Note' | 'Infinix Hot' | 'Infinix Smart' | 'Infinix S';
  releaseYear: number;
  releaseDate: string;
  releaseStatus?: OfficialReleaseStatus;
  screenSize: number;
  width: number;
  height: number;
  aspectRatio: string;
  refreshRate: number;
  touchSamplingRate: number | null;
  chipset: string;
  gpu: string;
  recommendedDpi: number;
  hasHardwareGyro: boolean | null;
  category: 'flagship' | 'gaming' | 'midrange' | 'budget';
  popular?: boolean;
  gen: number;
  rd: number;
  s2x: number;
  s4x: number;
  snip: number;
  fl: number;
  fire: number;
  note?: string;
}

function buildInfinixPhone(item: InfinixChartInput): PhoneModel {
  const nativePpi = Math.round(Math.hypot(item.width, item.height) / item.screenSize);
  const gyroType =
    item.hasHardwareGyro === true
      ? 'PHYSICAL_HARDWARE'
      : item.hasHardwareGyro === false
        ? 'VIRTUAL_SOFTWARE_ONLY'
        : 'INCONCLUSIVE';

  return {
    id: item.id,
    brand: 'Infinix',
    name: `Infinix ${item.name}`,
    series: item.series,
    releaseYear: item.releaseYear,
    releaseDate: item.releaseDate,
    releaseStatus:
      item.releaseStatus ??
      (item.releaseYear >= 2026
        ? 'announced_pending'
        : item.releaseYear <= 2021
          ? 'discontinued'
          : 'commercially_released'),
    screenSize: item.screenSize,
    resolution: `${item.width} x ${item.height}`,
    aspectRatio: item.aspectRatio,
    aspectRatioSource: 'CALCULATED',
    refreshRate: item.refreshRate,
    touchSamplingRate: item.touchSamplingRate,
    touchSamplingRateVerified: item.touchSamplingRate !== null,
    chipset: item.chipset,
    gpu: item.gpu,
    nativePpi,
    ppiSource: 'MANUFACTURER_PUBLISHED',
    ppiDerivation: {
      method: 'PYTHAGOREAN_PPI',
      formula: 'sqrt(w^2 + h^2) / diagonal',
      inputs: {
        width: item.width,
        height: item.height,
        diagonal: item.screenSize,
      },
    },
    recommendedDpi: item.recommendedDpi,
    hasHardwareGyro: item.hasHardwareGyro,
    gyroscopeType: gyroType,
    category: item.category,
    specsSource: 'Infinix Official Specs',
    specsSourceUrl: 'https://www.infinixmobility.com',
    verificationStatus: item.hasHardwareGyro === null ? 'partially_verified' : 'verified',
    popular: Boolean(item.popular),
    customSensitivityPreset: {
      general: item.gen,
      redDot: item.rd,
      scope2x: item.s2x,
      scope4x: item.s4x,
      sniperScope: item.snip,
      freeLook: item.fl,
    },
    customFireButtonPreset: item.fire,
    auditNotes: `Recommended starter settings — not official or device-tested values.${item.note ? ` ${item.note}` : ''}`,
  };
}

